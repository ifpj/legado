<#
.SYNOPSIS
CF Gateway local development helper for the Windows test workspace.

.DESCRIPTION
The git worktree that contains this script is the only source checkout.
Machine-specific files stay out of git:
  target/      cargo build cache (one shared cache, incremental)
  .local/tools CMake, NASM and libclang used by the native dependencies
  .local/bin   the running service binary, pid file and logs
  .cargo/      generated local cargo config (written by `setup`)

Commands:
  setup   write .cargo/config.toml from .local/tools
  build   cargo build --release (incremental, codegen-units=16)
  test    cargo fmt --check, cargo test --locked, Node syntax and contract checks
  run     build, replace the single service on the port in place, wait for /v1/status
  stop    stop the service listening on the port
  status  print /v1/status
  push    test, then git push origin cf (requires a clean tree on branch cf)

Examples:
  scripts/dev.ps1 test
  scripts/dev.ps1 run
  scripts/dev.ps1 push
#>
param(
    [Parameter(Position = 0)]
    [ValidateSet('setup', 'build', 'test', 'run', 'stop', 'status', 'push')]
    [string]$Command = 'test',
    [int]$Port = 19705,
    [string]$Listen = '127.0.0.1'
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$toolsDir = Join-Path $root '.local\tools'
$binDir = Join-Path $root '.local\bin'
$serviceExe = Join-Path $binDir 'cf-gateway.exe'
$pidFile = Join-Path $binDir 'service.json'
$cmakeExe = Join-Path $toolsDir 'cmake\bin\cmake.exe'
$nasmExe = Join-Path $toolsDir 'nasm\nasm.exe'
$libclangDir = Join-Path $toolsDir 'libclang'

function Use-BuildEnvironment {
    # Tool paths reach cargo only through .cargo/config.toml. Setting PATH or
    # LIBCLANG_PATH here would change build-script fingerprints between a plain
    # `cargo` shell and this script and force BoringSSL to rebuild.
    foreach ($tool in @($cmakeExe, $nasmExe, (Join-Path $libclangDir 'libclang.dll'))) {
        if (-not (Test-Path -LiteralPath $tool)) {
            throw "Missing build tool $tool. Put CMake, NASM and libclang under .local/tools (see docs/DEVELOPMENT.md)."
        }
    }
    if (-not (Test-Path -LiteralPath (Join-Path $root '.cargo\config.toml'))) { Write-LocalCargoConfig }
    Remove-Item Env:CARGO_TARGET_DIR, Env:LIBCLANG_PATH -ErrorAction SilentlyContinue
}

function Invoke-Step([string]$Label, [scriptblock]$Action) {
    $watch = [Diagnostics.Stopwatch]::StartNew()
    Write-Host "== $Label"
    & $Action
    if ($LASTEXITCODE) { throw "$Label failed (exit $LASTEXITCODE)" }
    Write-Host ("== {0} done in {1:n1}s" -f $Label, $watch.Elapsed.TotalSeconds)
}

function Write-LocalCargoConfig {
    $configDir = Join-Path $root '.cargo'
    New-Item -ItemType Directory -Path $configDir -Force | Out-Null
    $config = @(
        '# Generated by scripts/dev.ps1 setup. Local only; ignored by git and the Docker context.',
        '[env]',
        'CMAKE = { value = ".local/tools/cmake/bin/cmake.exe", relative = true }',
        'ASM_NASM = { value = ".local/tools/nasm/nasm.exe", relative = true }',
        'LIBCLANG_PATH = { value = ".local/tools/libclang", relative = true }',
        '',
        '[profile.release]',
        'incremental = true'
    )
    Set-Content -LiteralPath (Join-Path $configDir 'config.toml') -Value $config -Encoding utf8
    Write-Host "wrote $(Join-Path $configDir 'config.toml')"
}

function Invoke-Build {
    Use-BuildEnvironment
    Invoke-Step 'cargo build --release' { cargo build --release --locked --bin cf-gateway }
    $built = Join-Path $root 'target\release\cf-gateway.exe'
    $hash = (Get-FileHash -LiteralPath $built -Algorithm SHA256).Hash.Substring(0, 12).ToLowerInvariant()
    Write-Host "binary $built buildId $hash"
    return $built
}

function Invoke-Test {
    Use-BuildEnvironment
    Invoke-Step 'cargo fmt --check' { cargo fmt --check }
    Invoke-Step 'cargo test --locked' { cargo test --locked }
    Invoke-Step 'node --check' {
        foreach ($file in @(Get-ChildItem (Join-Path $root 'assets') -Filter *.js) + @(Get-ChildItem (Join-Path $root 'tests') -Filter *.cjs)) {
            node --check $file.FullName
            if ($LASTEXITCODE) { throw "node --check failed: $($file.Name)" }
        }
    }
    foreach ($contract in 'source-contracts', 'twkan-cleanup', 'content-cleanup') {
        Invoke-Step "node tests/$contract.cjs" { node (Join-Path $root "tests\$contract.cjs") }
    }
}

function Get-ServiceProcess {
    $listener = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $listener) { return $null }
    $process = Get-Process -Id $listener.OwningProcess -ErrorAction SilentlyContinue
    if ($process -and $process.ProcessName -ne 'cf-gateway') {
        throw "Port $Port is used by $($process.ProcessName) (pid $($process.Id)), not CF Gateway."
    }
    return $process
}

function Stop-Gateway {
    $process = Get-ServiceProcess
    if ($process) {
        Write-Host "stopping cf-gateway pid $($process.Id) on port $Port"
        Stop-Process -Id $process.Id
        $process.WaitForExit(10000) | Out-Null
    }
    Remove-Item -LiteralPath $pidFile -ErrorAction SilentlyContinue
}

function Get-Status {
    return Invoke-RestMethod "http://127.0.0.1:$Port/v1/status" -TimeoutSec 10
}

function Start-Gateway([string]$Binary) {
    New-Item -ItemType Directory -Path $binDir -Force | Out-Null
    Stop-Gateway
    Copy-Item -LiteralPath $Binary -Destination $serviceExe -Force
    $process = Start-Process -FilePath $serviceExe -ArgumentList @('serve', '--host', $Listen, '--port', $Port) `
        -WorkingDirectory $binDir -WindowStyle Hidden -PassThru `
        -RedirectStandardOutput (Join-Path $binDir 'cf-gateway.out.log') `
        -RedirectStandardError (Join-Path $binDir 'cf-gateway.err.log')
    $deadline = (Get-Date).AddSeconds(30)
    do {
        Start-Sleep -Milliseconds 500
        try { $status = Get-Status } catch { $status = $null }
    } while (-not $status -and (Get-Date) -lt $deadline -and -not $process.HasExited)
    if (-not $status) { throw "Service did not answer /v1/status within 30s; see $binDir\cf-gateway.err.log" }
    @{ pid = $process.Id; port = $Port; listen = $Listen; executable = $serviceExe; version = $status.version; buildId = $status.buildId; startedAt = (Get-Date).ToString('s') } |
        ConvertTo-Json | Set-Content -LiteralPath $pidFile -Encoding utf8
    Write-Host "cf-gateway $($status.version) build $($status.buildId) pid $($process.Id) listening on ${Listen}:$Port"
}

switch ($Command) {
    'setup' { Write-LocalCargoConfig }
    'build' { Invoke-Build | Out-Null }
    'test' { Invoke-Test }
    'run' { $binary = Invoke-Build; Start-Gateway $binary }
    'stop' { Stop-Gateway }
    'status' { Get-Status | Select-Object version, buildId, uptimeSeconds, requests, success, failed, active | Format-List }
    'push' {
        Push-Location $root
        try {
            $branch = git branch --show-current
            if ($branch -ne 'cf') { throw "Push only from branch cf (current: $branch)." }
            if (git status --porcelain) { throw 'Commit or stash local changes before pushing.' }
            Invoke-Test
            Invoke-Step 'git push origin cf' { git push origin cf }
        } finally { Pop-Location }
    }
}
